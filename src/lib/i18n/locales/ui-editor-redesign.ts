export const editorRedesignUi: Record<string, Record<string, string>> = {};
// Proper names remain unchanged in every interface language.
function add(language: string, text: string) {
  const row = text.trim().split("\n");
  if (row.length !== keys.length)
    throw new Error(
      "Editor locale length mismatch: " + language + " " + row.length
    );
  editorRedesignUi[language] = {
    ...Object.fromEntries(keys.map((key, index) => [key, row[index]])),
    ...editorControlUi[language as InterfaceLanguage],
    ...editorStyleCardUi[language as InterfaceLanguage],
    ...editorModelPickerUi[language as InterfaceLanguage],
    ...editorColorUi[language as InterfaceLanguage],
    "This section changed while you were editing it. Reopen it to use the latest version.":
      sectionConflict[language],
  };
}
